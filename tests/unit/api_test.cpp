// The public API (include/stomp/stomp.hpp): what the stomp tool and other programs use.
#include <stomp/stomp.hpp>

#include <string>

#include "check.hpp"

namespace {
const char* const R0603 = "footprint \"R0603\"\n  body 1.6 x 0.8 x 0.45\n  pins 2\n  lead endcap 0.3\nend\n";
}

TEST(api_compiles_a_file_into_footprints) {
  const stomp::Compiled out = stomp::compile(std::string_view(R0603));
  CHECK(!out.has_errors());
  CHECK(out.diagnostics.empty());
  CHECK_EQ(out.footprints.size(), std::size_t(1));
  const stomp::Footprint& fp = out.footprints[0];
  CHECK_EQ(fp.name(), std::string("R0603"));
  CHECK(fp.built() && fp.ok());
  // the model in both formats, and the KiCad file with the model embedded
  CHECK(fp.vrml().rfind("#VRML V2.0 utf8\n# R0603, generated by stomp.", 0) == 0);
  const auto stl = fp.stl();
  CHECK(stl.size() > 84 && (stl.size() - 84) % 50 == 0);
  const stomp::KicadFile k = fp.kicad();
  CHECK_EQ(k.file, std::string("R0603.kicad_mod"));
  CHECK(k.model);
  CHECK(k.text.rfind("(footprint \"R0603\"\n\t(version 20241229)", 0) == 0);
  CHECK(k.text.find("(model \"kicad-embed://R0603.wrl\"") != std::string::npos);
}

TEST(api_reports_problems_with_lines_columns_and_notes) {
  const stomp::Compiled out = stomp::compile(std::u16string_view(
      u"width = 1\nfootprint \"A\"\n  pad 1 rect widtth x 1\n  pad 1 at (0, 0)\nend\n"
      u"footprint \"B µ\"\n  pad 1 rect 1 x 1\n  pad 1 at (0, 0)\n  pad 1 at (1, 0)\nend\n"));
  CHECK(out.has_errors());
  CHECK_EQ(out.diagnostics.size(), std::size_t(3));
  const stomp::Diagnostic& d = out.diagnostics[0];
  CHECK(d.error);
  CHECK_EQ(d.message, std::string("unknown name `widtth` \xE2\x80\x94 did you mean `width`?"));
  CHECK_EQ(d.line, std::size_t(3));
  CHECK_EQ(d.column, std::size_t(14));
  CHECK_EQ(d.end_column, std::size_t(20));
  CHECK_EQ(d.footprint, std::string("A"));
  // a second placement of pad 1 points back at the first
  const stomp::Diagnostic& twice = out.diagnostics[1];
  CHECK_EQ(twice.footprint, std::string("B \xC2\xB5"));
  CHECK_EQ(twice.notes.size(), std::size_t(1));
  CHECK_EQ(twice.notes[0].line, std::size_t(8));
  // footprints with errors are still there, not ok
  CHECK_EQ(out.footprints.size(), std::size_t(2));
  CHECK(out.footprints[0].built() && !out.footprints[0].ok());
  CHECK(!out.footprints[1].ok());
}

TEST(api_library_problems_are_placed_in_their_file) {
  stomp::Options o;
  o.library = stomp::builtin_library();
  o.library[0].source += u"\nfeature oops(\n";
  o.cache = false;
  const stomp::Compiled out = stomp::compile(std::string_view(R0603), o);
  CHECK(!out.library_diagnostics.empty());
  const stomp::Diagnostic& d = out.library_diagnostics[0];
  CHECK_EQ(d.file, o.library[0].name);
  CHECK(d.line > 1);
}
