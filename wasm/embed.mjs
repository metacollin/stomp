// Makes demo/js/stomp-core.js: Emscripten's loader with the wasm embedded, gzipped and
// in base64, inflated at load time with DecompressionStream. One classic script, so the
// editor works from file:// and in the single-file bundle.
//   node wasm/embed.mjs stomp_wasm.js stomp_wasm.wasm demo/js/stomp-core.js
import { readFileSync, writeFileSync } from 'node:fs';
import { gzipSync } from 'node:zlib';
import { createHash } from 'node:crypto';

const [glueFile, wasmFile, outFile] = process.argv.slice(2);
const glue = readFileSync(glueFile, 'utf8');
const wasm = readFileSync(wasmFile);
// mtime 0 and a fixed level keep the output the same for the same wasm
const gz = gzipSync(wasm, { level: 9 });
gz.writeUInt32LE(0, 4);
const b64 = gz.toString('base64');
const sha = createHash('sha256').update(wasm).digest('hex');

const out = `/* Generated by wasm/embed.mjs from the C++ engine. Don't edit.
   wasm: ${wasm.length} bytes, sha256 ${sha} */
(function (root) {
${glue}
var WASM_GZ = '${b64}';
function bytesOf(b64) {
  var s = atob(b64), a = new Uint8Array(s.length);
  for (var i = 0; i < s.length; i++) a[i] = s.charCodeAt(i);
  return a;
}
function inflate(gz) {
  var stream = new Blob([gz]).stream().pipeThrough(new DecompressionStream('gzip'));
  return new Response(stream).arrayBuffer().then(function (b) { return new Uint8Array(b); });
}
var core = inflate(bytesOf(WASM_GZ)).then(function (wasmBinary) { return StompCore({ wasmBinary: wasmBinary }); });
(root.Stomp = root.Stomp || {}).core = core;
if (typeof module === 'object' && module.exports) module.exports = core;
})(typeof self !== 'undefined' ? self : globalThis);
`;
writeFileSync(outFile, out);
console.log(`${outFile}: wasm ${wasm.length} bytes, embedded ${b64.length} characters`);
