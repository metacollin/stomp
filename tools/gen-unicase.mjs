// Writes src/unicase_data.inc: JavaScript's toLowerCase/toUpperCase per code point, and
// the Cased and Case_Ignorable ranges (for the final-sigma rule), taken from the Node
// that runs this. Regenerate when moving to a newer Unicode version.
//   node tools/gen-unicase.mjs > src/unicase_data.inc
const units = (s) => [...s].length && Array.from({ length: s.length }, (_, i) => s.charCodeAt(i));
const lower = [], upper = [];
for (let cp = 0; cp <= 0x10ffff; cp++) {
  if (cp >= 0xd800 && cp <= 0xdfff) continue;
  const s = String.fromCodePoint(cp);
  const lo = s.toLowerCase(), up = s.toUpperCase();
  if (lo !== s) lower.push([cp, units(lo)]);
  if (up !== s) upper.push([cp, units(up)]);
}
const ranges = (re) => {
  const out = [];
  let start = -1;
  for (let cp = 0; cp <= 0x110000; cp++) {
    const on = cp <= 0x10ffff && !(cp >= 0xd800 && cp <= 0xdfff) && re.test(String.fromCodePoint(cp));
    if (on && start < 0) start = cp;
    if (!on && start >= 0) { out.push([start, cp - 1]); start = -1; }
  }
  return out;
};
const cased = ranges(/^\p{Cased}$/u), ignorable = ranges(/^\p{Case_Ignorable}$/u);
const maxLen = Math.max(...lower.concat(upper).map((e) => e[1].length));
const hex = (n) => '0x' + n.toString(16).toUpperCase();
const table = (name, rows) => `const CaseMap ${name}[] = {\n` +
  rows.map(([cp, u]) => `  {${hex(cp)}, ${u.length}, {${u.map(hex).join(', ')}}},`).join('\n') + '\n};\n';
const rtable = (name, rows) => `const Range ${name}[] = {\n` +
  rows.map(([a, b]) => `  {${hex(a)}, ${hex(b)}},`).join('\n') + '\n};\n';
process.stdout.write(`// Generated by tools/gen-unicase.mjs from Node ${process.version} (Unicode ${process.versions.unicode}). Don't edit.
// JavaScript's toLowerCase/toUpperCase for each code point whose mapping isn't itself,
// and the Cased and Case_Ignorable ranges the final-sigma rule needs.
constexpr int kMaxCaseLen = ${maxLen};
${table('kLower', lower)}
${table('kUpper', upper)}
${rtable('kCased', cased)}
${rtable('kCaseIgnorable', ignorable)}`);
console.error(`lower ${lower.length}, upper ${upper.length}, cased ${cased.length} ranges, ignorable ${ignorable.length} ranges, longest ${maxLen}`);
